-- Aquisição simples de plantas, sem pagamento e sem exclusividade.
-- Execute este script no SQL Editor do Supabase antes de testar a função de aquisição.

create table if not exists public.plantas_adquiridas (
  id bigint generated by default as identity primary key,
  usuario_id uuid not null references auth.users(id) on delete cascade,
  planta_id bigint not null references public.plantas(id) on delete cascade,
  adquirido_em timestamptz not null default now(),
  constraint plantas_adquiridas_usuario_planta_unica unique (usuario_id, planta_id)
);

alter table public.plantas_adquiridas enable row level security;

drop policy if exists "Usuário consulta suas plantas adquiridas" on public.plantas_adquiridas;
create policy "Usuário consulta suas plantas adquiridas"
  on public.plantas_adquiridas
  for select
  to authenticated
  using (usuario_id = (select auth.uid()));

drop policy if exists "Usuário adquire planta para si" on public.plantas_adquiridas;
create policy "Usuário adquire planta para si"
  on public.plantas_adquiridas
  for insert
  to authenticated
  with check (
    usuario_id = (select auth.uid())
    and exists (
      select 1
      from public.plantas p
      where p.id = planta_id
        and p.ativa = true
    )
  );

grant select, insert on public.plantas_adquiridas to authenticated;
grant usage, select on sequence public.plantas_adquiridas_id_seq to authenticated;
